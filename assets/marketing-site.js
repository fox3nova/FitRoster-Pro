  const supported = Object.keys(translations);
  const languageAliases = {
    "zh-TW": "zh-Hant",
    "zh-HK": "zh-Hant",
    "zh-MO": "zh-Hant",
    "zh-CN": "zh-Hans",
    "zh-SG": "zh-Hans"
  };

  function normalizeLanguage(value) {
    if (!value) return "en";
    if (supported.includes(value)) return value;
    if (languageAliases[value]) return languageAliases[value];
    const exact = supported.find((language) => value.toLowerCase() === language.toLowerCase());
    if (exact) return exact;
    const primary = value.split("-")[0].toLowerCase();
    if (primary === "zh") return value.toLowerCase().includes("hant") ? "zh-Hant" : "zh-Hans";
    return supported.find((language) => language.toLowerCase() === primary) || "en";
  }

  function copyFor(language) {
    return Object.assign({}, base, translations[language] || {});
  }

  function imageSource(_language, key) {
    if (key === "coach-dashboard") {
      return "assets/marketing/en/coach-dashboard-current.webp";
    }
    if (key === "coach-records") {
      return "assets/marketing/en/coach-records-current.webp";
    }
    return `assets/marketing/en/${key}.jpg`;
  }

  function applyLanguage(language) {
    const normalized = normalizeLanguage(language);
    const copy = copyFor(normalized);
    document.documentElement.lang = normalized;
    document.documentElement.dir = "ltr";
    document.title = copy.pageTitle;

    const description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute("content", copy.pageDescription);

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.getAttribute("data-i18n");
      if (copy[key]) element.textContent = copy[key];
    });

    document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
      const rules = element.getAttribute("data-i18n-attr").split(",");
      rules.forEach((rule) => {
        const [attribute, key] = rule.split(":").map((part) => part.trim());
        if (attribute && key && copy[key]) element.setAttribute(attribute, copy[key]);
      });
    });

    document.querySelectorAll("[data-marketing-img]").forEach((image) => {
      image.setAttribute("src", imageSource(normalized, image.getAttribute("data-marketing-img")));
    });

    const select = document.getElementById("language-select");
    if (select) select.value = normalized;
    localStorage.setItem("fitroster.pro.marketing.language", normalized);
  }

  const select = document.getElementById("language-select");
  if (select) {
    select.addEventListener("change", (event) => applyLanguage(event.target.value));
  }

  const stored = localStorage.getItem("fitroster.pro.marketing.language");
  applyLanguage(stored || navigator.language || "en");
