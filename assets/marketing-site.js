  function normalizeLanguage(value) {
    if (!value) return "en";
    if (supported.includes(value)) return value;
    if (languageAliases[value]) return languageAliases[value];
    const exact = supported.find((language) => value.toLowerCase() === language.toLowerCase());
    if (exact) return exact;
    const primary = value.split("-")[0].toLowerCase();
    if (primary === "zh") return value.toLowerCase().includes("hant") ? "zh-Hant" : "zh-Hans";
    return supported.find((language) => language.toLowerCase() === primary) || "en";
  }

